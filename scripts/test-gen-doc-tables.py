#!/usr/bin/env python3
"""Seeded RED/GREEN cases for scripts/gen-doc-tables.py.

Each case copies the fixture tree (scripts/testdata/doc-tables: a small
contract with comment tags, a 01 capability table and the four docs with
empty generated blocks) into a throwaway folder, builds its image with the
pinned buf, and runs the real script. Exit codes: 0 clean, 1 a tag error, a
missing marker or a stale block, 2 the contract could not be loaded.
"""
from __future__ import annotations

import re
import subprocess
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from proto_image_testkit import ROOT, FixtureTree, clean_env  # noqa: E402

GEN = ROOT / "scripts/gen-doc-tables.py"
DATA = ROOT / "scripts/testdata/doc-tables"
SVC = "api/fleet/hub/v1/service.proto"
WATCH = "api/fleet/hub/v1/watch.proto"
EVENTS = "api/fleet/agent/v1/events.proto"
AGENT = "api/fleet/agent/v1/agent.proto"
D02K, D02D = "docs/specs/02k-v1-surface-and-cli.md", "docs/specs/02d-hub-authz.md"
D02I, D02 = "docs/specs/02i-delivery-and-sequencing.md", "docs/specs/02-contracts.md"
BLOCKS = [  # (doc, source in the marker, expected body)
    (D02K, SVC, "02k-rpcs.md"), (D02K, WATCH, "02k-topics.md"),
    (D02D, SVC, "02d-rpcs.md"), (D02D, WATCH, "02d-topics.md"),
    (D02I, EVENTS, "02i.md"), (D02, "api/fleet/*/v1/*.proto", "02.md"),
]


TABLES = ["RPCs by release", "Watch topics by release", "scope per RPC", "scope per Watch topic",
          "delivery class per event body", "capability map"]  # same order as BLOCKS
ONE_BLOCK_SEEDS = [  # a tag edit that changes only BLOCKS[i]: (file, old, new)
    (SVC, "  // [RELEASE v1 13a]\n", "  // [RELEASE v1 12]\n"),
    (WATCH, "[RELEASE v1 19]", "[RELEASE v1 12]"),
    (SVC, "  // [SCOPE ADMIN]\n", "  // [SCOPE READ]\n"),
    (WATCH, "`ADMIN`: all; otherwise the caller's own device", "`ADMIN`: all; otherwise its own device"),
    (EVENTS, "a sample every 30 s; the next one replaces it", "a sample every 60 s"),
    (AGENT, "  CONNECT_REASON_START = 1;\n  // [CAP A6]\n", "  // [CAP A6]\n  CONNECT_REASON_START = 1;\n"),
]


def body(text, src):
    begin = "<!-- BEGIN GENERATED by scripts/gen-doc-tables.py from %s; do not edit by hand -->\n" % src
    end = "<!-- END GENERATED by scripts/gen-doc-tables.py from %s -->\n" % src
    start = text.index(begin) + len(begin)
    return text[start:text.index(end, start)]


class GenDocTablesTests(unittest.TestCase):
    def setUp(self):
        self.tree = FixtureTree(DATA)
        self.addCleanup(self.tree.cleanup)
        self.image = self.tree.root / "image.json"
        self.rebuild()

    def rebuild(self):
        self.tree.build_image(self.image)

    def run_gen(self, *args):
        return subprocess.run([sys.executable, str(GEN), "--root", str(self.tree.root), *args],
                              env=clean_env(FLEET_PROTO_IMAGE=str(self.image)), capture_output=True, text=True)

    def assert_rc(self, want, out):
        self.assertEqual(want, out.returncode, "stdout:\n%s\nstderr:\n%s" % (out.stdout, out.stderr))
        return out.stdout + out.stderr

    def read(self, rel):
        return (self.tree.root / rel).read_text()

    def seed(self, rel, old, new, want_error):
        self.tree.edit(rel, old, new)
        self.rebuild()
        out = self.assert_rc(1, self.run_gen("--check"))
        self.assertRegex(out, want_error)
        return out

    def test_write_generates_every_table_as_expected_then_check_passes(self):
        self.assert_rc(1, self.run_gen("--check"))
        self.assert_rc(0, self.run_gen("--write"))
        for doc, src, expected in BLOCKS:
            with self.subTest(doc=doc, src=src):
                self.assertEqual((DATA / "expected" / expected).read_text(), body(self.read(doc), src))
        self.assert_rc(0, self.run_gen("--check"))
        self.assertIn("| hand row | kept |", self.read(D02D))
        self.assertIn("Outside `Event`: hand-kept.", self.read(D02I))

    def test_a_comment_change_changes_its_table_and_check_fails_until_write(self):
        self.assert_rc(0, self.run_gen("--write"))
        self.tree.edit(SVC, "`ADMIN` for archived goals", "`ADMIN` for every goal")
        self.rebuild()
        out = self.assert_rc(1, self.run_gen("--check"))
        self.assertIn("%s: scope per RPC (from %s) is out of date" % (D02D, SVC), out)
        self.assertNotIn(D02I, out)
        self.assert_rc(0, self.run_gen("--write"))
        self.assertIn("| `ListGoals` | `READ` | `ADMIN` for every goal |", self.read(D02D))
        self.assert_rc(0, self.run_gen("--check"))

    def stale(self, i):
        doc, src, _ = BLOCKS[i]
        return "%s: %s (from %s) is out of date" % (doc, TABLES[i], src)

    def assert_only_stale(self, i, out):
        for j in range(len(BLOCKS)):
            (self.assertIn if j == i else self.assertNotIn)(self.stale(j), out)

    def bodies(self):
        return [body(self.read(doc), src) for doc, src, _ in BLOCKS]

    def test_a_tag_edit_changes_only_its_block_for_every_block(self):
        self.assert_rc(0, self.run_gen("--write"))
        for i, (rel, old, new) in enumerate(ONE_BLOCK_SEEDS):
            with self.subTest(table=TABLES[i]):
                before = self.bodies()
                self.tree.edit(rel, old, new)
                self.rebuild()
                self.assert_only_stale(i, self.assert_rc(1, self.run_gen("--check")))
                self.assert_rc(0, self.run_gen("--write"))
                after = self.bodies()
                for j in range(len(BLOCKS)):
                    (self.assertNotEqual if j == i else self.assertEqual)(before[j], after[j], TABLES[j])
                self.assert_rc(0, self.run_gen("--check"))

    def test_a_hand_edit_inside_any_block_fails(self):
        self.assert_rc(0, self.run_gen("--write"))
        for i, (doc, src, _) in enumerate(BLOCKS):
            with self.subTest(table=TABLES[i]):
                text = self.read(doc)
                old = body(text, src)
                rows = old.split("\n")
                rows[2] += " edited by hand"
                self.tree.write(doc, text.replace(old, "\n".join(rows), 1))
                self.assert_only_stale(i, self.assert_rc(1, self.run_gen("--check")))
                self.tree.write(doc, text)
                self.assert_rc(0, self.run_gen("--check"))

    def test_missing_markers_fail_for_check_and_write(self):
        text = self.read(D02I)
        self.tree.write(D02I, re.sub(r"<!-- (BEGIN|END) GENERATED[^\n]*\n", "", text))
        for mode in ("--check", "--write"):
            out = self.assert_rc(1, self.run_gen(mode))
            self.assertIn("%s: no BEGIN GENERATED marker for delivery class per event body" % D02I, out)

    def test_a_missing_required_tag_fails(self):
        self.seed(SVC, "  // [RELEASE v1 13a]\n", "", r"DrainMachine.*needs a \[RELEASE\] tag")

    def test_a_missing_delivery_tag_fails(self):
        self.seed(EVENTS, "    // [DELIVERY SHED] a sample every 30 s; the next one replaces it\n", "",
                  r"resource_sample.*needs a \[DELIVERY\] tag")

    def test_an_unknown_key_fails(self):
        self.seed(SVC, "  // [SCOPE ADMIN]\n", "  // [OWNER ADMIN]\n", r"DrainMachine.*unknown tag key OWNER")

    def test_an_old_bracket_scope_fails(self):
        self.seed(SVC, "  // [SCOPE ADMIN]\n", "  // [ADMIN]\n", r"DrainMachine.*unknown tag key ADMIN")

    def test_a_tag_key_in_prose_fails(self):
        self.seed(SVC, "  // Finish current work, take nothing new.\n",
                  "  // Finish current work; see [CAP D1] too.\n", r"DrainMachine.*tag key \[CAP\] outside the tag block")

    def test_a_tag_after_a_blank_line_is_in_prose(self):
        self.seed(SVC, "  // [RELEASE v1 13a]\n", "  //\n  // [RELEASE v1 13a]\n",
                  r"DrainMachine.*tag key \[RELEASE\] outside the tag block")

    def test_self_joined_with_a_scope_is_rejected(self):
        self.seed(SVC, "[SCOPE self] `self` is the device itself", "[SCOPE self|ADMIN] `self` is the device itself",
                  r"GetDevice.*never joined with \|")

    def test_a_scope_that_is_not_in_the_scope_enum_fails(self):
        self.seed(SVC, "  // [SCOPE ADMIN]\n", "  // [SCOPE OWNER]\n", r"DrainMachine.*OWNER is not a Scope value")

    def test_coalesce_without_a_key_fails(self):
        self.seed(EVENTS, "[DELIVERY COALESCE ready:<pane>]", "[DELIVERY COALESCE]", r"harness_ready.*COALESCE needs a key")

    def test_shed_with_a_key_fails(self):
        self.seed(EVENTS, "[DELIVERY SHED]", "[DELIVERY SHED sample:<machine>]", r"resource_sample.*SHED takes no key")

    def test_a_delivery_class_not_in_the_enum_fails(self):
        self.seed(EVENTS, "[DELIVERY SHED]", "[DELIVERY SOMETIMES]", r"resource_sample.*SOMETIMES is not a DeliveryClass")

    def test_a_cap_id_not_in_01_fails(self):
        self.seed(EVENTS, "// [CAP B2]", "// [CAP B9]", r"ResourceSample.*B9 is not a capability id in docs/specs/01")

    def test_a_malformed_release_fails(self):
        self.seed(SVC, "[RELEASE v1 13a]", "[RELEASE v2 13a]", r"DrainMachine.*RELEASE needs v1 or v3")

    def test_release_lines_with_two_releases_fail(self):
        self.seed(SVC, "[RELEASE v1 22] dispatched goals", "[RELEASE v3 none] dispatched goals",
                  r"ListGoals.*one release")

    def test_a_tag_where_it_does_not_belong_fails(self):
        self.seed(AGENT, "// [CAP A7]\n", "// [SCOPE READ]\n", r"Bye.*\[SCOPE\] is not allowed on a message")

    def test_a_tag_in_a_trailing_comment_fails(self):
        self.seed(AGENT, "  string probe_id = 1;\n", "  string probe_id = 1; // [CAP D1]\n",
                  r"EnsureProbe.probe_id.*outside the tag block")

    def test_a_tag_cut_off_by_a_blank_line_fails(self):
        self.seed(AGENT, "// [CAP A7]\nmessage Bye {", "// [CAP A7]\n\nmessage Bye {",
                  r"message Bye: tag key \[CAP\] in a comment a blank line cuts off")

    def test_two_cap_lines_fail(self):
        self.seed(AGENT, "// [CAP A7]\nmessage Bye {", "// [CAP A7]\n// [CAP A3]\nmessage Bye {",
                  r"message Bye: has more than one \[CAP\] tag")

    def test_full_enum_names_and_unspecified_are_not_tag_values(self):
        cases = [
            (SVC, "  // [SCOPE ADMIN]\n", "  // [SCOPE SCOPE_READ]\n", r"DrainMachine: SCOPE SCOPE_READ: write SCOPE_READ without SCOPE_"),
            (SVC, "  // [SCOPE ADMIN]\n", "  // [SCOPE SCOPE_UNSPECIFIED]\n", r"DrainMachine: SCOPE SCOPE_UNSPECIFIED: write SCOPE_UNSPECIFIED without SCOPE_"),
            (SVC, "  // [SCOPE ADMIN]\n", "  // [SCOPE UNSPECIFIED]\n", r"DrainMachine: SCOPE UNSPECIFIED: UNSPECIFIED is never a tag value"),
            (EVENTS, "[DELIVERY SHED]", "[DELIVERY DELIVERY_CLASS_UNSPECIFIED]", r"resource_sample: DELIVERY DELIVERY_CLASS_UNSPECIFIED: write DELIVERY_CLASS_UNSPECIFIED without DELIVERY_CLASS_"),
            (EVENTS, "[DELIVERY COALESCE ready:<pane>]", "[DELIVERY DELIVERY_CLASS_COALESCE]", r"harness_ready: DELIVERY DELIVERY_CLASS_COALESCE: write DELIVERY_CLASS_COALESCE without DELIVERY_CLASS_"),
        ]
        for rel, old, new, want in cases:
            with self.subTest(tag=new.strip()):
                original = self.read(rel)
                self.seed(rel, old, new, want)
                self.tree.write(rel, original)

    def test_release_rows_come_from_the_plan(self):
        for old, new, want in (("[RELEASE v1 13a]", "[RELEASE v1 99]", r"DrainMachine: RELEASE v1 99: 99 is not a row of the PR sequence"),
                               ("[RELEASE v3 none]", "[RELEASE v3 12]", r"GetDevice: RELEASE v3 12: v3 has no plan row yet; write \[RELEASE v3 none\]"),
                               ("[RELEASE v1 13a]", "[RELEASE v1 none]", r"DrainMachine: RELEASE v1 none: v1 names a plan row")):
            with self.subTest(tag=new):
                original = self.read(SVC)
                self.seed(SVC, old, new, want)
                self.tree.write(SVC, original)

    def test_a_missing_plan_fails_closed(self):
        (self.tree.root / "docs/plan/v1-implementation-plan.md").unlink()
        self.assertIn("cannot read docs/plan/v1-implementation-plan.md", self.assert_rc(2, self.run_gen("--check")))

    def test_a_contract_without_the_anchors_fails_closed(self):
        self.tree.edit(EVENTS, "message Event {", "message Occurrence {")
        self.tree.edit(AGENT, "    Event event = 2;", "    Occurrence event = 2;")
        self.rebuild()
        out = self.assert_rc(2, self.run_gen("--check"))
        self.assertIn("fleet.agent.v1.Event", out)

    def test_a_broken_image_fails_closed(self):
        self.image.write_text("{not json")
        self.assertIn("gen-doc-tables: cannot read the image", self.assert_rc(2, self.run_gen("--check")))

    def test_mode_is_required(self):
        self.assertIn("one of the arguments --check --write is required", self.assert_rc(2, self.run_gen()))


if __name__ == "__main__":
    unittest.main()
