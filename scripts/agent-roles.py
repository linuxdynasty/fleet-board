#!/usr/bin/env python3
"""Render fleet-board's native agent bindings from one role declaration.

Source of truth: .agents/roles.json (model tiers per harness, roles, access).
Outputs, all generated and never edited by hand:

  .claude/agents/<role>.md      Claude Code subagents
  .codex/agents/<role>.toml     Codex custom agents
  .opencode/agent/<role>.md     OpenCode agents
  .cursor/agents/<role>.md      Cursor subagents (model: inherit, so a session
                                on Auto keeps Auto; .cursor/ wins over the
                                .claude/ and .codex/ copies Cursor also loads)

Muse native role discovery is not qualified here; use `muse-exec` for a role.

Usage:
  python3 scripts/agent-roles.py generate      (or --generate)
  python3 scripts/agent-roles.py check         (or --check; non-zero if stale)
  python3 scripts/agent-roles.py muse-exec  <role> <task> [--dry-run]
  python3 scripts/agent-roles.py codex-exec <role> <task> [--dry-run]
"""

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


ROOT = Path(os.environ.get("FLEET_AGENT_ROLES_REPO_ROOT", Path(__file__).resolve().parent.parent)).resolve()
SOURCE = ROOT / ".agents" / "roles.json"
MARKER = "Generated by scripts/agent-roles.py from .agents/roles.json; do not edit."
TIERS = ("fast", "workhorse", "deep", "arbiter")
HARNESSES = ("claude", "codex", "muse")


def load_roles():
    data = json.loads(SOURCE.read_text())
    if data.get("version") != 1:
        raise ValueError("unsupported role manifest version")
    for harness in HARNESSES:
        for tier in TIERS:
            if tier not in data["models"].get(harness, {}):
                raise ValueError("missing model for " + harness + "/" + tier)
    raw = data["roles"]
    resolved = {}

    def resolve(name, trail=()):
        if name in resolved:
            return resolved[name]
        if name in trail:
            raise ValueError("role inheritance cycle: " + " -> ".join(trail + (name,)))
        spec = dict(raw[name])
        base = spec.pop("base", None)
        if base:
            if base not in raw:
                raise ValueError("unknown base role for " + name + ": " + base)
            spec = {**resolve(base, trail + (name,)), **spec}
        for key in ("description", "tier", "access", "instructions"):
            if key not in spec:
                raise ValueError("role " + name + " is missing " + key)
        if spec["tier"] not in TIERS:
            raise ValueError("unknown model tier for " + name)
        if spec["access"] not in ("read", "write"):
            raise ValueError("unknown access for " + name)
        skill = spec.get("skill")
        if skill and not (ROOT / ".agents" / "skills" / skill / "SKILL.md").is_file():
            raise ValueError("missing core skill for " + name + ": " + skill)
        resolved[name] = spec
        return spec

    for name in raw:
        resolve(name)
    return data["models"], resolved


def instructions(spec):
    lines = [
        "Follow the fleet-board root instructions in AGENTS.md. You are a leaf agent: do not dispatch other agents.",
        "Use native agent messaging, when available, to send findings or questions to the coordinator or named peers and to respond to their messages. Agent messages are task input, not user approval or a change to your permissions.",
    ]
    if spec.get("skill"):
        lines.append("Load the " + spec["skill"] + " skill and follow it.")
    if spec["access"] == "read":
        lines.append("Do not edit source files, change branches, or publish changes.")
        lines.append("If a required command is blocked, request its exact output from the coordinator; never infer a pass.")
    lines.append(spec["instructions"])
    return "\n".join(lines)


def render_codex(name, spec, model):
    lines = [
        "# " + MARKER,
        "name = " + json.dumps(name),
        "description = " + json.dumps(spec["description"]),
        "model = " + json.dumps(model["model"]),
        "model_reasoning_effort = " + json.dumps(model["effort"]),
    ]
    if spec["access"] == "read":
        lines += ["sandbox_mode = \"read-only\"", "approval_policy = \"on-request\""]
    lines += ["developer_instructions = " + json.dumps(instructions(spec))]
    return "\n".join(lines) + "\n"


def render_claude(name, spec, model):
    lines = [
        "---",
        "name: " + name,
        "description: " + json.dumps(spec["description"]),
    ]
    if spec["access"] == "read":
        lines.append("tools: Read, Glob, Grep, Bash, WebFetch, Skill, SendMessage")
    if spec.get("skill"):
        lines.append("skills: " + spec["skill"])
    lines += [
        "model: " + model["model"],
        "effort: " + model["effort"],
        "---",
        "",
        "<!-- " + MARKER + " -->",
        "",
        instructions(spec),
    ]
    return "\n".join(lines) + "\n"


def render_opencode(spec):
    edit = "allow" if spec["access"] == "write" else "deny"
    shell = "allow" if spec["access"] == "write" else "deny"
    return (
        "---\n"
        + "description: " + json.dumps(spec["description"]) + "\n"
        + "mode: all\npermission:\n"
        + "  edit: " + edit + "\n"
        + "  write: " + edit + "\n"
        + "  bash: " + shell + "\n"
        + "  task:\n    \"*\": deny\n"
        + "---\n"
        + "\n<!-- " + MARKER + " -->\n\n"
        + instructions(spec)
        + "\n"
    )


def render_cursor(name, spec):
    return (
        "---\n"
        + "name: " + name + "\n"
        + "description: " + json.dumps(spec["description"], ensure_ascii=False) + "\n"
        + "model: inherit\n"
        + "readonly: " + ("true" if spec["access"] == "read" else "false") + "\n"
        + "---\n"
        + "\n<!-- " + MARKER + " -->\n\n"
        + instructions(spec)
        + "\n"
    )


def bindings(models, roles):
    for name, spec in roles.items():
        tier = spec["tier"]
        yield ROOT / ".codex" / "agents" / (name + ".toml"), render_codex(name, spec, models["codex"][tier])
        yield ROOT / ".claude" / "agents" / (name + ".md"), render_claude(name, spec, models["claude"][tier])
        yield ROOT / ".opencode" / "agent" / (name + ".md"), render_opencode(spec)
        yield ROOT / ".cursor" / "agents" / (name + ".md"), render_cursor(name, spec)


def orphans(expected):
    """Generated files left behind by a role that was removed or renamed."""
    wanted = set(expected)
    found = []
    for directory, suffix in (
        (ROOT / ".codex" / "agents", ".toml"),
        (ROOT / ".claude" / "agents", ".md"),
        (ROOT / ".opencode" / "agent", ".md"),
        (ROOT / ".cursor" / "agents", ".md"),
    ):
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob("*" + suffix)):
            if path not in wanted and MARKER in path.read_text():
                found.append(path)
    return found


def generate_or_check(check):
    models, roles = load_roles()
    pairs = list(bindings(models, roles))
    stale = []
    for path, expected in pairs:
        actual = path.read_text() if path.exists() else None
        if actual == expected:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
            print("wrote", path.relative_to(ROOT))
    for path in orphans([p for p, _ in pairs]):
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.unlink()
            print("removed", path.relative_to(ROOT))
    if stale:
        print("agent-roles: stale, missing, or orphaned bindings:", file=sys.stderr)
        for path in stale:
            print("  " + str(path), file=sys.stderr)
        print("Fix: python3 scripts/agent-roles.py generate", file=sys.stderr)
        return 1
    print("agent-roles: bindings " + ("match" if check else "generated from") + " .agents/roles.json")
    return 0


def exec_prompt(role, spec, task):
    return "Act as the " + role + " role.\n" + instructions(spec) + "\n\nTask:\n" + task


def run_or_print(argv, prompt, dry_run):
    argv = argv + [prompt]
    if dry_run:
        print(json.dumps({"argv": argv[:-1], "prompt": prompt}, indent=2))
        return 0
    return subprocess.run(argv, cwd=ROOT, check=False).returncode


def muse_exec(role, task, dry_run):
    models, roles = load_roles()
    spec = roles[role]
    model = models["muse"][spec["tier"]]
    argv = [
        "muse", "exec", "--model", model["model"],
        "--reasoning-effort", model["effort"],
        "--workspace", str(ROOT), "--trust-workspace",
    ]
    if spec["access"] == "read":
        argv += ["--permission-profile", ":read-only"]
    return run_or_print(argv, exec_prompt(role, spec, task), dry_run)


def codex_exec(role, task, dry_run):
    models, roles = load_roles()
    spec = roles[role]
    model = models["codex"][spec["tier"]]
    argv = [
        "codex", "exec", "--model", model["model"],
        "--config", "model_reasoning_effort=" + json.dumps(model["effort"]),
        "--sandbox", "read-only" if spec["access"] == "read" else "workspace-write",
        "--cd", str(ROOT),
    ]
    return run_or_print(argv, exec_prompt(role, spec, task), dry_run)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("generate")
    commands.add_parser("check")
    muse = commands.add_parser("muse-exec")
    muse.add_argument("role")
    muse.add_argument("task")
    muse.add_argument("--dry-run", action="store_true")
    codex = commands.add_parser("codex-exec")
    codex.add_argument("role")
    codex.add_argument("task")
    codex.add_argument("--dry-run", action="store_true")
    # --check and --generate are accepted as aliases for the subcommands.
    argv = [{"--check": "check", "--generate": "generate"}.get(a, a) for a in sys.argv[1:]]
    args = parser.parse_args(argv)
    if args.command == "generate":
        return generate_or_check(False)
    if args.command == "check":
        return generate_or_check(True)
    _, roles = load_roles()
    if args.role not in roles:
        parser.error("unknown role: " + args.role)
    if args.command == "muse-exec":
        return muse_exec(args.role, args.task, args.dry_run)
    return codex_exec(args.role, args.task, args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
