#!/usr/bin/env bash
#
# test-check-generated-headers.sh: seeded RED/GREEN cases for
# scripts/check-generated-headers.sh, in a throwaway git repo (never this one).
#
# Usage: scripts/test-check-generated-headers.sh        exit 0 only if every case passes
set -u

root="$(cd "$(dirname "$0")/.." && pwd)"
check="$root/scripts/check-generated-headers.sh"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
repo="$work/repo"

pass=0
fail=0
ok() { pass=$((pass + 1)); }
bad() {
  fail=$((fail + 1))
  printf 'FAIL: %s\n' "$1" >&2
}

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

rm -rf "$repo"
mkdir -p "$repo/internal/a" "$repo/gen/go" "$repo/internal/a/testdata"
git -C "$repo" init -q
printf 'package a\n' > "$repo/internal/a/a.go"
printf '// Code generated by buf. DO NOT EDIT.\n\npackage gen\n' > "$repo/gen/go/x.pb.go"
printf '// Code generated by hand. DO NOT EDIT.\n\npackage fix\n' > "$repo/internal/a/testdata/f.go"

# run <name> <want rc> <substring of the output, or empty>
run() {
  local name="$1" want="$2" sub="$3" out rc
  out="$(FLEET_GENERATED_HEADERS_REPO_ROOT="$repo" "$check" 2>&1)"
  rc=$?
  if [ "$rc" -ne "$want" ]; then
    bad "$name: exit $rc, want $want ($out)"
    return
  fi
  if [ -n "$sub" ]; then
    case "$out" in
      *"$sub"*) ;;
      *)
        bad "$name: output lacks '$sub' ($out)"
        return
        ;;
    esac
  fi
  ok
}

run "clean tree; gen/ and testdata/ are skipped" 0 "none outside gen/"

printf '// Code generated by hand. DO NOT EDIT.\n\npackage a\n\nimport "os/exec"\n\nvar _ = exec.Command\n' > "$repo/internal/a/sneaky.go"
run "an untracked file with the header" 1 "internal/a/sneaky.go"
git -C "$repo" add -A
run "the same file, tracked" 1 "internal/a/sneaky.go"

printf 'package a\n\n// Code generated by hand. DO NOT EDIT.\n' > "$repo/internal/a/sneaky.go"
run "the header after the package clause is not a generated-code header" 0 ""

printf '// Package a.\n//\n// Code generated by hand. DO NOT EDIT.\npackage a\n' > "$repo/internal/a/sneaky.go"
run "the header inside a doc comment, still before the package clause" 1 "internal/a/sneaky.go"

rm "$repo/internal/a/sneaky.go"
run "removed again" 0 ""

printf '%d passed, %d failed\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
