#!/usr/bin/env python3
"""Seeded RED/GREEN cases for scripts/agent-roles.py (generate and check)."""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/agent-roles.py"


class AgentRolesTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo = Path(self.tmp.name)
        shutil.copytree(ROOT / ".agents", self.repo / ".agents", symlinks=True)
        self.roles = json.loads((self.repo / ".agents/roles.json").read_text())["roles"]

    def run_script(self, *args):
        env = dict(os.environ, FLEET_AGENT_ROLES_REPO_ROOT=str(self.repo))
        return subprocess.run([sys.executable, str(SCRIPT), *args], env=env, capture_output=True, text=True)

    def cursor_files(self):
        return sorted((self.repo / ".cursor/agents").glob("*.md"))

    def access(self, name):
        spec = self.roles[name]
        while "access" not in spec:
            spec = self.roles[spec["base"]]
        return spec["access"]

    def test_generate_writes_a_cursor_agent_per_role_that_inherits_the_model(self):
        self.assertEqual(self.run_script("generate").returncode, 0)
        for name in self.roles:
            text = (self.repo / ".cursor/agents" / (name + ".md")).read_text()
            self.assertTrue(text.startswith("---\nname: " + name + "\n"), name)
            self.assertIn("\nmodel: inherit\n", text, name)
            readonly = "true" if self.access(name) == "read" else "false"
            self.assertIn("\nreadonly: " + readonly + "\n", text, name)
            self.assertIn("Generated by scripts/agent-roles.py", text, name)

    def test_cursor_agents_name_no_claude_or_codex_model(self):
        self.assertEqual(self.run_script("generate").returncode, 0)
        models = json.loads((self.repo / ".agents/roles.json").read_text())["models"]
        pinned = {m["model"] for harness in ("claude", "codex") for m in models[harness].values()}
        self.assertEqual(len(self.cursor_files()), len(self.roles))
        for path in self.cursor_files():
            front = path.read_text().split("---\n")[1]
            for model in pinned:
                self.assertNotIn("model: " + model + "\n", front, path.name)

    def test_check_fails_when_a_cursor_agent_is_missing_and_passes_after_generate(self):
        self.assertEqual(self.run_script("generate").returncode, 0)
        name = next(iter(self.roles))
        (self.repo / ".cursor/agents" / (name + ".md")).unlink()
        red = self.run_script("check")
        self.assertEqual(red.returncode, 1)
        self.assertIn(".cursor/agents/" + name + ".md", red.stderr)
        self.assertEqual(self.run_script("generate").returncode, 0)
        self.assertEqual(self.run_script("check").returncode, 0)

    def test_an_orphaned_cursor_agent_is_reported_then_removed(self):
        self.assertEqual(self.run_script("generate").returncode, 0)
        orphan = self.repo / ".cursor/agents/gone-role.md"
        orphan.parent.mkdir(parents=True, exist_ok=True)
        orphan.write_text("---\nname: gone-role\n---\n<!-- Generated by scripts/agent-roles.py"
                          " from .agents/roles.json; do not edit. -->\n")
        self.assertEqual(self.run_script("check").returncode, 1)
        self.assertEqual(self.run_script("generate").returncode, 0)
        self.assertFalse(orphan.exists())

    def test_a_hand_written_cursor_agent_is_left_alone(self):
        self.assertEqual(self.run_script("generate").returncode, 0)
        mine = self.repo / ".cursor/agents/my-own.md"
        mine.parent.mkdir(parents=True, exist_ok=True)
        mine.write_text("---\nname: my-own\nmodel: inherit\n---\nmine\n")
        self.assertEqual(self.run_script("check").returncode, 0)
        self.assertTrue(mine.exists())

    def test_a_description_with_yaml_specials_round_trips(self):
        manifest = json.loads((self.repo / ".agents/roles.json").read_text())
        name = next(iter(manifest["roles"]))
        tricky = 'Use: "quoted" # not a comment --- é ✓ 😀 \\ back'
        manifest["roles"][name]["description"] = tricky
        (self.repo / ".agents/roles.json").write_text(json.dumps(manifest))
        self.assertEqual(self.run_script("generate").returncode, 0)
        front = (self.repo / ".cursor/agents" / (name + ".md")).read_text().split("---\n")[1]
        line = next(x for x in front.splitlines() if x.startswith("description: "))
        self.assertEqual(json.loads(line[len("description: "):]), tricky)
        self.assertIn("😀", line)


if __name__ == "__main__":
    unittest.main()
